#!/usr/bin/env node
/**
 * Ingest owner-supplied YouTube Audio Library tracks (owner 2026-09-10 chose
 * path A). Reads real title/artist from the file's tags, normalises loudness,
 * transcodes to 192k mp3, files it as yal-<slug>-NN.mp3, and records the real
 * credit in assets/music/manifest.json so every description can name the track
 * honestly (owner: "不tag流行音乐名字").
 *
 * Usage: node scripts/ingest-music.mjs --in <file-or-dir> [--mood upbeat|cinematic|calm|epic]
 *   [--prefix yal|el|vq|wc] [--source "<credit source>"] [--title "..."] [--artist "..."]
 *   [--license "..."] [--attribution "..."] [--style <styleCode>] [--bpm N] [--sourceUrl <url>]
 *   [--name <file-slug>] [--ai-generated true|false] [--provenance '<json or text>'] [--notes "..."]
 *
 * 2026-10-17: also files licensed NON-YAL tracks (ElevenLabs Music output (commercial use needs a
 * paid plan, MUSIC.md §1), vidIQ-generated, Wikimedia Commons CC0/PD/CC-BY). Pass --prefix and
 * --source so the manifest credit is honest; --attribution is the exact line a
 * CC-BY track must carry in every description. Defaults keep the YAL behaviour.
 * Output name: <prefix>-<slug(--name | --style | title)>.mp3 when that slug already ends in -NN
 * (e.g. --style pov-walk-groove-01 -> el-pov-walk-groove-01.mp3), else <prefix>-<slug>-NN.mp3 with
 * the next free NN for that base. Every entry records aiGenerated (default true for el/vq, false for
 * yal/wc) and vault: false; scripts/music-vault.mjs encrypt flips vault to true (el-* tracks stay
 * encrypted in the public repo — MUSIC.md §4).
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, extname, basename } from 'node:path';

const args = {};
for (let i = 2; i < process.argv.length; i++) {
  if (!process.argv[i].startsWith('--')) continue;
  const next = process.argv[i + 1];
  // A flag followed by another --flag (or by nothing) is a bare boolean flag, never "eats" the next flag.
  args[process.argv[i].slice(2)] = next === undefined || next.startsWith('--') ? 'true' : (i++, next);
}
if (!args.in || args.in === 'true') fail('Usage: node scripts/ingest-music.mjs --in <file-or-dir> [--mood upbeat|cinematic|calm|epic]');
const PREFIX = (args.prefix || 'yal').replace(/[^a-z]/g, '') || 'yal';
const AI_PREFIXES = ['el', 'vq']; // ElevenLabs / vidIQ output is AI-generated by definition (D1 disclosure)
// Honest per-prefix defaults when --source / --artist are omitted (never credit a non-YAL track to the YAL).
const DEFAULT_SOURCE = { yal: 'YouTube Audio Library', el: 'ElevenLabs Music (AI-generated)', vq: 'vidIQ generate_music', wc: 'Wikimedia Commons' };
if (!DEFAULT_SOURCE[PREFIX]) fail(`--prefix must be one of ${Object.keys(DEFAULT_SOURCE).join('|')} (got "${PREFIX}")`);
if (PREFIX === 'wc' && !args.artist) fail('--prefix wc needs --artist (the real author from the Commons file page) and --attribution for CC BY.');
if (args['ai-generated'] !== undefined && !['true', 'false'].includes(args['ai-generated'])) {
  fail(`--ai-generated must be exactly "true" or "false" (got "${args['ai-generated']}")`);
}
if (AI_PREFIXES.includes(PREFIX) && args['ai-generated'] === 'false') {
  fail(`--prefix ${PREFIX} tracks are AI-generated by definition; refusing --ai-generated false (it would skip the containsSyntheticMedia disclosure).`);
}

const MUSIC_DIR = 'automation/youtube/assets/music';
const MANIFEST = join(MUSIC_DIR, 'manifest.json');
await mkdir(MUSIC_DIR, { recursive: true });

const AUDIO = new Set(['.mp3', '.m4a', '.wav', '.aac', '.ogg', '.flac']);
let files = [];
try {
  const entries = await readdir(args.in);
  files = entries.filter((f) => AUDIO.has(extname(f).toLowerCase())).map((f) => join(args.in, f));
} catch { files = [args.in]; }
if (!files.length) fail(`No audio files found at ${args.in}`);

let manifest = { note: 'Music library manifest — credit lines and AI flags per track; see automation/youtube/MUSIC.md.', tracks: [] };
if (existsSync(MANIFEST)) manifest = JSON.parse(await readFile(MANIFEST, 'utf8'));

const slugCore = (s) => (s || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
// Truncate the stem only, so an explicit trailing -NN (e.g. docu-underscore-cinematic-calm-01) survives.
const slug = (s) => {
  const m = slugCore(s).match(/^(.*?)(-\d{2})?$/);
  const core = m[1].slice(0, 40).replace(/-+$/, '');
  return core ? core + (m[2] || '') : (m[2] ? `track${m[2]}` : 'track');
};
const taken = new Set(manifest.tracks.map((t) => basename(String(t.file || ''))));
const isTaken = (name) => taken.has(name) || existsSync(join(MUSIC_DIR, name));
const nextName = (base) => {
  if (/-\d{2}$/.test(base) && !isTaken(`${base}.mp3`)) return `${base}.mp3`;
  for (let i = 1; i < 100; i++) { const n = `${base}-${String(i).padStart(2, '0')}.mp3`; if (!isTaken(n)) return n; }
  fail(`no free -NN slot for ${base}`);
};
const parseProvenance = (v) => { try { return JSON.parse(v); } catch { return v; } };
const results = [];
for (const f of files) {
  const probe = JSON.parse(run('ffprobe', ['-v', 'error', '-show_entries', 'format=duration:format_tags=title,artist,album', '-of', 'json', f]));
  const tags = probe.format?.tags || {};
  const title = args.title || tags.title || basename(f, extname(f)).replace(/[_-]+/g, ' ').trim();
  const artist = args.artist || tags.artist || DEFAULT_SOURCE[PREFIX];
  const prefix = PREFIX;
  const source = args.source || DEFAULT_SOURCE[PREFIX];
  const dur = Number(probe.format?.duration || 0);
  const mood = args.mood || 'mixed';
  const fileName = nextName(`${prefix}-${slug(args.name || args.style || title)}`);
  taken.add(fileName);
  const out = join(MUSIC_DIR, fileName);
  const aiGenerated = args['ai-generated'] !== undefined ? args['ai-generated'] === 'true' : AI_PREFIXES.includes(prefix);
  // loudnorm so beds sit consistently under cues; 192k keeps the repo light
  run('ffmpeg', ['-y', '-i', f, '-af', 'loudnorm=I=-16:TP=-1.5:LRA=11', '-b:a', '192k', out]);
  results.push({ file: out.replace('automation/youtube/', ''), title, artist, mood, durationSec: Math.round(dur), source,
    ...(args.style ? { style: args.style } : {}), ...(args.bpm ? { bpm: Number(args.bpm) } : {}),
    ...(args.license ? { license: args.license } : {}), ...(args.attribution ? { attribution: args.attribution } : {}),
    ...(args.sourceUrl ? { sourceUrl: args.sourceUrl } : {}), aiGenerated, vault: false,
    ...(args.provenance ? { provenance: parseProvenance(args.provenance) } : {}), ...(args.notes ? { notes: args.notes } : {}),
    addedAt: new Date().toISOString().slice(0, 10) });
  console.log(`+ ${out}  ← "${title}" — ${artist} (${Math.round(dur)}s)`);
}
manifest.tracks.push(...results);
await writeFile(MANIFEST, JSON.stringify(manifest, null, 1));
console.log(`\nmanifest: ${manifest.tracks.length} tracks. Credit lines per source: automation/youtube/MUSIC.md §6.`);
if (results.some((r) => r.aiGenerated && /^assets\/music\/el-/.test(r.file))) console.log('el-* tracks: run node scripts/music-vault.mjs encrypt --in <file> next; never commit the plain mp3.');

function run(bin, a) {
  try { return execFileSync(bin, a, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }); }
  catch (e) { fail(`${bin} failed:\n${(e.stderr || e.message).slice(0, 400)}`); }
}
function fail(m) { console.error(m); process.exit(1); }
